use atomis::compiler::{compile, CompileOptions};
#[test]
fn independent_name_resolution_corpus() {
    let options = CompileOptions {
        file_name: "names.ato".into(),
        output_file: "names.ts".into(),
        source_map: true,
    };
    let cases = [
("undefined-variable","output(missing)",false),
("undefined-function","missingFunction()",false),
("local","fn f() -> number { atom x = 2\nreturn x }\noutput(f())",true),
("parameter","fn f(x: number) -> number { return x }\noutput(f(1))",true),
("outer","atom x = 1\nfn f() -> number { return x }\noutput(f())",true),
("guard-escape","fn f() { guard false else { atom hidden = 1 }\noutput(hidden) }",false),
("raw-block-escape","if (true) { let hidden = 1; }\noutput(hidden)",false),
("duplicate-atom","atom x = 1\natom x = 2",false),
("duplicate-raw","let x=1;let x=2;",false),
("duplicate-parameter","fn f(x:number,x:number){}",false),
("parameter-local-duplicate","fn f(x:number){ atom x=1 }",false),
("const-assign","const x=1;\nx=2;",false),
("const-update","const x=1;\nx++;",false),
("const-prefix","const x=1;\n++x;",false),
("const-property","const x={value:1};\nx.value=2;",true),
("mutable","atom x=1\nx+=2\noutput(x)",true),
("undefined-initializer","atom x=missing",false),
("undefined-return","fn f(){return missing}",false),
("undefined-default","fn f(x:number=missing) {return x}",false),
("undefined-guard","guard missing else { output(1) }",false),
("undefined-discriminant","match missing { _ => console.log(1) }",false),
("undefined-pattern","match 1 { missing => console.log(1), _ => console.log(2) }",false),
("undefined-arm","match 1 { _ => missing() }",false),
("undefined-template","output(`hello ${missing}`)",false),
("nested-template","output(`${`${missing}`}`)",false),
("escaped-template","output(`hello \\${literal}`)",true),
("property","atom x={value:1}\noutput(x.value)",true),
("computed-property","atom x={value:1}\noutput(x[missing])",false),
("object-shorthand","atom x={missing}",false),
("object-key","atom x={\nvalue:1,\nother:2\n}\noutput(x.other)",true),
("object-value","atom x={value:missing}",false),
("ternary","output(true ? missing : 1)",false),
("condition","if (missing) { console.log(1); }",false),
("assignment-target","missing=1",false),
("array","atom xs=[1,missing]",false),
("arguments","fn f(x:number){}\nf(missing)",false),
("regex-opaque","output(/missing/.test('missing'))",true),
("comment-opaque","// missing()\noutput('missing')",true),
("import-alias","@import { basename as leaf } from \"node:path\"\noutput(leaf(\"a/b\"))",true),
("import-alias-original","@import { basename as leaf } from \"node:path\"\noutput(basename(\"a/b\"))",false),
("destructure","const {value: local}={value:1};\noutput(local)",true),
("array-destructure","const [local]=[1];\noutput(local)",true),
("catch","try { throw new Error('x'); } catch (err) { console.log(err); }",true),
("catch-escape","try { throw 1; } catch (err) { console.log(err); }\noutput(err)",false),
("no-parameters","fn f() -> number { return 1 }\noutput(f())",true),
("multi-parameters","fn sum(a:number,b:number)->number {return a+b}\noutput(sum(1,2))",true),
("too-few","fn f(a:number){}\nf()",true),
("too-many","fn f(a:number){}\nf(1,2)",true),
("wrong-argument","fn f(a:number){}\nf('x')",true),
("default-argument","fn f(a:number=2)->number{return a}\noutput(f())",true),
("wrong-return","fn f()->number{return 'x'}",true),
("missing-return","fn f()->number{}",true),
("empty-return","fn f()->number{return}",true),
("guard-return","fn f(x:number)->number{guard x>0 else{return 0}\nreturn x}",true),
("nested-function","fn outer(a:number)->number {fn inner(b:number)->number{return a+b}\nreturn inner(2)}\noutput(outer(1))",true),
("nested-function-escape","fn outer(){fn inner(){} }\ninner()",false),
("shadow","atom x=1\nfn f(x:string)->string{return x}\noutput(f('x'))",true),
("block-shadow","let x=1;\nif(true){let x='a';console.log(x);}\noutput(x)",true),
("scope-reuse","if(true){let x=1;console.log(x);}\nlet x=2;\noutput(x)",true),
("sibling-escape","fn a(){let x=1;}\nfn b(){return x}",false),
("var-function","fn f(){if(true){var x=1;}\nreturn x}",true),
("for-zero","let sum=0;\nfor(let i=0;i<0;i++){sum+=i;}\noutput(sum)",true),
("for-one","let sum=0;\nfor(let i=0;i<1;i++){sum+=i;}\noutput(sum)",true),
("for-many","let sum=0;\nfor(let i=0;i<=3;i++){sum+=i;}\noutput(sum)",true),
("for-nested","let sum=0;\nfor(let i=0;i<3;i++){for(let j=0;j<2;j++){sum+=i+j;}}\noutput(sum)",true),
("for-break-continue","for(let i=0;i<4;i++){if(i===1)continue;if(i===3)break;console.log(i);}",true),
("for-escape","for(let i=0;i<1;i++){console.log(i);}\noutput(i)",false),
("for-single","for(let i=0;i<1;i++)console.log(i);\noutput(i)",false),
("for-missing","for(let i=0;i<missing;i++){console.log(i);}",false),
("for-of","for(const item of [1,2]){console.log(item);}",true),
("for-in","for(const key in {x:1}){console.log(key);}",true),
("while","let i=0;\nwhile(i<3){i++;}\noutput(i)",true),
("do-while","let i=0;\ndo{i++;}while(i<1);\noutput(i)",true),
("loop-nonboolean","while(0){break;}",true),
("loop-type-error","for(let i=0;i<{};i++){break;}",true),
("arithmetic","output((10-2)*3/2%5)\noutput(2**3)",true),
("compare","output(1<2 && 2>=1)\noutput(1===1 || false)\noutput(!false)",true),
("string","atom s='a'+'b'\noutput(`${s}!`)",true),
("invalid-add","output(true+1)",true),
("invalid-arithmetic","output('a'-1)",true),
("invalid-compare","output(1<'a')",true),
("assignment-type","atom x=1\nx='a'",true),
("literal-type","atom x:number='a'",false),
("conversion","output(Number('42'))\noutput(String(42))",true),
("missing-conversion","output(Int32('42'))",false),
("number-boundary","output(Number.MAX_SAFE_INTEGER+1)\noutput(Number.MAX_VALUE*2)\noutput(1/0)\noutput(0/0)",true),
("bigint-zero","output(1n/0n)",true),
("assertion-reference","atom x=1\noutput((x as number)+missing)",false),
("arrow","const f=(x:number)=>x+1;\noutput(f(1))",true),
("arrow-escape","const f=(x:number)=>x+1;\noutput(x)",false),
("single-arrow","const f=(x:number)=>[1].map(y=>x+y);\noutput(f(1))",true),
("block-arrow","const f=(x:number)=>{return x;};\noutput(f(1))",true),
("return-result","fn f()->Result<number,string>{return Ok(1)}",true),
("loop-immediate-escape","for(let i=0;i<1;i++){console.log(i);}i",false),
("arrow-expression-escape","const x=[1].map(item=>item)+item;",false),
("named-function","const f=function local(){return local};\noutput(f())",true),
("named-function-escape","const f=function local(){};\noutput(local)",false),
("method","const obj={f(x:number){return x}};\noutput(obj.f(1))",true),
("class","class C { value:number=1; f(x:number){return this.value+x;} }\noutput(new C().f(2))",true),
("method-undefined","const obj={f(x:number){return missing+x}};",false),
("method-escape","const obj={f(x:number){return x}};\noutput(x)",false)
];
    for (name, source, valid) in cases {
        let r = compile(source, &options).unwrap();
        assert_eq!(
            !r.analysis.has_errors, valid,
            "{name}: {:?}",
            r.analysis.diagnostics
        );
        if !valid {
            assert!(r.code.is_empty());
            assert!(r.map.is_none());
            assert!(r
                .analysis
                .diagnostics
                .iter()
                .any(|d| d.line > 0 && d.col > 0));
        }
    }
}
